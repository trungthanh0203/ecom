  payment_status text not null default 'unpaid' check (payment_status in ('unpaid','pending_verification','paid','failed','refunded')),
  shipping_status text not null default 'not_shipped' check (shipping_status in ('not_shipped','in_transit','delivered','failed','returned')),
  payment_method text not null check (payment_method in ('cod','bank_transfer')),
  recipient_name text not null,
  phone text not null,
  email text,
  province text not null,
  ward text,
  address_line text not null,
  note text,
  lang text not null default 'vi',
  currency text not null default 'VND',
  subtotal numeric(14,0) not null check (subtotal >= 0),
  vat_rate numeric(5,2) not null check (vat_rate >= 0),
  vat_amount numeric(14,0) not null check (vat_amount >= 0),
  shipping_fee numeric(14,0) not null check (shipping_fee >= 0),
  total numeric(14,0) not null check (total >= 0),
  assigned_to uuid references public.staff(user_id) on delete set null,
  consent_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
