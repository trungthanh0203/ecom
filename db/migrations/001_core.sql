-- ===== Sản phẩm =====
create table public.products (
  id bigint generated by default as identity primary key,
  sku text not null check (length(trim(sku)) > 0),
  category_id bigint references public.categories(id) on delete restrict,
  brand_id bigint references public.brands(id) on delete restrict,
  price numeric(14,0) check (price is null or price >= 0),           -- giá niêm yết CHƯA gồm VAT, đơn vị = currency
  sale_price numeric(14,0) check (sale_price is null or sale_price >= 0),
  sale_start timestamptz,
  sale_end timestamptz,
  currency text not null default 'VND',
  retail_enabled boolean not null default true,
  status text not null default 'draft' check (status in ('draft','published','hidden','archived')),
  featured boolean not null default false,
  is_new boolean not null default false,
  unit text,
  package_info text,
  attrs jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint products_sku_unique unique (sku),
  -- WRS 4: sản phẩm bán lẻ không được xuất bản nếu thiếu giá hợp lệ
  constraint products_publish_needs_price check (status <> 'published' or not retail_enabled or (price is not null and price > 0)),
  -- giá KM phải có giá gốc, thấp hơn giá gốc, có thời hạn kết thúc
  constraint products_sale_valid check (sale_price is null or (price is not null and sale_price < price and sale_end is not null and (sale_start is null or sale_start < sale_end)))
);
create index products_status_idx on public.products(status);
create index products_category_idx on public.products(category_id);
create index products_brand_idx on public.products(brand_id);

