-- 001_core.sql — bảng dữ liệu cốt lõi. Phụ thuộc: schema `auth` của Supabase (auth.users, auth.uid()).
-- Quy ước: ngôn ngữ = mã 2 ký tự; mọi bảng *_translations có status draft|reviewed|published;
-- giá/SKU CHỈ nằm ở bảng gốc, bản dịch chỉ chứa chữ.

create table public.staff (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('super_admin','admin','editor','contributor','sales','order_manager')),
  display_name text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.role_permissions (
  role text not null,
  perm text not null,
  primary key (role, perm)
);

create table public.site_settings (
  key text primary key,
  value jsonb not null,
  is_public boolean not null default false,   -- KHÔNG lưu secret ở đây
  updated_at timestamptz not null default now()
);

